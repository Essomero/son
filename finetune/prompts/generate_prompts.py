FREE_TALK_SLOTS = 10  # trailing free-record slots (any topic, up to a minute each)


def main() -> None:
    rows = []
    i = 0
    for cat, pool in CATEGORIES:
        for text in pool:
            rows.append({"id": i, "category": cat, "text": text})
            i += 1
    for _ in range(FREE_TALK_SLOTS):
        rows.append({"id": i, "category": "free", "text": ""})
        i += 1
    with open(OUT, "w") as f:
        for r in rows:
            f.write(json.dumps(r) + "\n")
    n_spoken = sum(1 for r in rows if r["text"])
    print(f"{len(rows)} prompts: {n_spoken} spoken + {len(rows) - n_spoken} free-talk")
    for cat, pool in CATEGORIES:
        print(f"  {cat:12s} {len(pool)}")
    print(f"-> {OUT}")


if __name__ == "__main__":
    main()
